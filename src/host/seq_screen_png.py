#!/usr/bin/env python3
"""Host preview of the SEQ page (src/ui_seq_draw.c) as a PNG. Test scaffolding only; needs Pillow.

The C harness (render_seq_screen.c) runs the real draw routine against a stand-in for Felucca's canvas: it rasterises
every rectangle, line and pixel itself and logs each text call. This script supplies the font metrics the harness
measures text with, then composites the logged text onto the harness's framebuffer.

    seq_screen_png.py metrics OUT.h             font advances / line metrics for the harness (AF_S 12 px, AF_M 15 px)
    seq_screen_png.py png FB.bin TEXT.log OUT.png [scale]

Felucca's own faces (Inter Tight, generated by its build) are not in this repo, so Segoe UI stands in: the layout and
widths are close, the glyph shapes are not the device's.
"""
import os
import struct
import sys

from PIL import Image, ImageDraw, ImageFont

FONT_DIRS = [os.environ.get("WINDIR", "C:/Windows") + "/Fonts", "/usr/share/fonts/truetype/dejavu"]
FACES = {"S": 12, "M": 15}                           # gfx.c: AF_S 12 px / 400, AF_M 15 px / 500


def load(px):
    for d in FONT_DIRS:
        for name in ("segoeui.ttf", "DejaVuSans.ttf", "arial.ttf"):
            p = os.path.join(d, name)
            if os.path.exists(p):
                return ImageFont.truetype(p, px)
    raise SystemExit("no TrueType face found")


def metrics(out):
    lines = ["/* generated by seq_screen_png.py metrics: stand-in font metrics for render_seq_screen.c */"]
    for name, px in FACES.items():
        f = load(px)
        asc, desc = f.getmetrics()
        _, t, _, b = f.getbbox("H", anchor="la")
        adv = [int(round(f.getlength(chr(c)))) for c in range(32, 127)]
        lines.append(f"#define AF_{name}_CAP_Y {t}")
        lines.append(f"#define AF_{name}_CAP_H {b - t}")
        lines.append(f"static const uint8_t SHIM_ADV_{name}[95] = {{{', '.join(map(str, adv))}}};")
        lines.append(f"#define SHIM_{name}_H {asc + desc}")
        lines.append(f"#define SHIM_{name}_ASC {asc}")
    open(out, "w").write("\n".join(lines) + "\n")


def png(fb_path, log_path, out, scale):
    raw = open(fb_path, "rb").read()
    img = Image.new("RGB", (240, 240))
    px = img.load()
    for i in range(240 * 240):
        (c,) = struct.unpack_from("<H", raw, i * 2)
        px[i % 240, i // 240] = (((c >> 11) & 31) * 255 // 31, ((c >> 5) & 63) * 255 // 63, (c & 31) * 255 // 31)
    fonts = {n: load(p) for n, p in FACES.items()}
    for line in open(log_path, encoding="utf-8"):
        # x y face rgb565 clipx0 clipy0 clipx1 clipy1 <tab> text ; x is the pen per character (the harness's advances)
        head, text = line.rstrip("\n").split("\t", 1)
        x, y, face, col, cx0, cy0, cx1, cy1 = head.split()
        x, y, col = int(x), int(y), int(col)
        rgb = (((col >> 11) & 31) * 255 // 31, ((col >> 5) & 63) * 255 // 63, (col & 31) * 255 // 31)
        layer = Image.new("RGBA", (240, 240), (0, 0, 0, 0))
        d = ImageDraw.Draw(layer)
        f = fonts[face]
        for ch in text:
            d.text((x, y), ch, font=f, fill=rgb + (255,), anchor="la")
            x += int(round(f.getlength(ch)))
        clip = Image.new("L", (240, 240), 0)
        ImageDraw.Draw(clip).rectangle((int(cx0), int(cy0), int(cx1) - 1, int(cy1) - 1), fill=255)
        alpha = Image.composite(layer.getchannel("A"), Image.new("L", (240, 240), 0), clip)
        layer.putalpha(alpha)
        img.paste(layer, (0, 0), layer)
    img.resize((240 * scale, 240 * scale), Image.NEAREST).save(out)


if __name__ == "__main__":
    if len(sys.argv) >= 3 and sys.argv[1] == "metrics":
        metrics(sys.argv[2])
    elif len(sys.argv) >= 5 and sys.argv[1] == "png":
        png(sys.argv[2], sys.argv[3], sys.argv[4], int(sys.argv[5]) if len(sys.argv) > 5 else 2)
    else:
        raise SystemExit(__doc__)
