/* Writes src/dsp/drive_tables.h: the AMP drive's makeup for every model (amplifier.h), in centi-dB at DRIVE 0, 8 ..
 * 128 (amp_drive_prepare goes straight between them). It is measured here, through the same amp_drive_step and
 * amp_drive_gain the voice runs: a band-limited 110 Hz saw peaking at -6 dBFS comes out at the RMS it went in with.
 *
 *   gcc -O2 -Isrc -Isrc/dsp src/host/gen_drive_tables.c -lm -o gen && ./gen > src/dsp/drive_tables.h
 */
#include <math.h>
#include <stdio.h>
#include "amplifier.h"

#define FS 44100
#define N (FS)
#define SKIP (FS / 4)

static const char *const names[DRIVE_COUNT] = {"SOFT", "HARD", "FOLD", "TAPE", "TUBE", "OVERDRIVE"};
static float saw[N];

static double rms_through(int model, int drive) {
    AmpDrive d = {amp_drive_gain(model, drive), 1.f, amp_drive_tape_a(drive), (uint8_t)model};
    float s[2] = {0.f, 0.f};
    double e = 0.;
    for (int i = 0; i < N; i++) {
        float y = amp_drive_step(&d, model, s, saw[i]);
        if (i >= SKIP) e += (double)y * y;
    }
    return sqrt(e / (N - SKIP));
}

int main(void) {
    double peak = 0., e = 0.;
    for (int i = 0; i < N; i++) {
        double v = 0.;
        for (int k = 1; k * 110 < FS / 2; k++) v += sin(2. * M_PI * 110. * k * i / FS) / k;
        saw[i] = (float)v;
        if (fabs(v) > peak) peak = fabs(v);
    }
    for (int i = 0; i < N; i++) {
        saw[i] = (float)(saw[i] * 16384. / peak);
        if (i >= SKIP) e += (double)saw[i] * saw[i];
    }
    double rms_in = sqrt(e / (N - SKIP));
    printf("/* Generated by src/host/gen_drive_tables.c: do not edit. The AMP drive's makeup per DRIVE_* model, centi-dB\n"
           " * at DRIVE 0, 8 .. 128 (0: bypassed, unused). */\n#pragma once\n\n");
    printf("static const int16_t drive_makeup_cdb[DRIVE_COUNT][17] = {\n");
    for (int m = 0; m < DRIVE_COUNT; m++) {
        printf("    {");
        for (int k = 0; k <= 16; k++)
            printf("%s%d", k ? ", " : "", (int)lround(2000. * log10(rms_in / rms_through(m, 8 * k))));
        printf("},   /* %s, 0 .. +%d dB */\n", names[m], drive_top_db[m]);
    }
    printf("};\n");
    return 0;
}
