/* The browser emulator's 240 x 240 screen, every page: the firmware's own renderers (src/ui_page_draw.c's
 * ui_screen_draw, which hands SEQ and ARP to src/ui_seq_draw.c and src/ui_arp_draw.c), run on
 * felucca_canvas_shim.h's stand-in for Felucca's canvas, so the page shows what the FM1 code draws. Compiled into the
 * wasm core by web/emu/build.sh.
 *
 * The renderer redraws only the regions that changed, so each call reports them: the page copies each region's pixels
 * from the framebuffer and draws that region's text over them (text cannot be rasterised here: Felucca's faces are
 * generated by its build), leaving the rest of its canvas as it was.
 *
 *   web_screen_draw(force, ms)   the same for whichever page is up, after ticking the UI clock by ms
 *   web_seq_draw(force)          run the renderer; force 1 on entering the page or after a palette change. Returns the
 *                                number of regions drawn (0: nothing changed)
 *   web_seq_fb()                 240 x 240 RGB565, row by row
 *   web_seq_blits()              per region: x, y, w, h, first text, text count (uint16 x 6)
 *   web_seq_text_pos()           per text: screen x, y of its line top (int16 x 2)
 *   web_seq_text_col()           per text: RGB565 (uint16)
 *   web_seq_text_face()          per text: 'S' 12 px or 'M' 15 px (uint8)
 *   web_seq_text_str()           per text: WEB_SEQ_TEXT_LEN bytes, NUL-terminated
 *   web_seq_palette(i)           0 ORANGE, 1 RED (ui_seq_draw.c SQPAL_*, spec 3)
 *   web_seq_knob_text(k)         knob k's value as the screen's knob card shows it ("C#3", "x8", "BOTH") */
