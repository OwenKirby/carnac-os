#!/usr/bin/env python3
"""Writes src/dsp/ctrl_tables.h: the control tick's per-knob and per-cent results as tables, so the tick does a load
instead of a hardware divide (~24 cycles each on the FM1, which does not turn constant divides into multiplies).
Every entry is the integer formula synth_voice.c used before, with C's truncating division: bit-exact.

  python src/dsp/gen_ctrl_tables.py
"""
from pathlib import Path

OUT = Path(__file__).with_name("ctrl_tables.h")
OUT_ENV = Path(__file__).with_name("env_sustain.h")
SEMI_Q16 = [65536, 69433, 73562, 77936, 82570, 87480, 92682, 98193, 104032, 110218, 116772, 123715, 131072]


def cdiv(a, b):
    """C's integer division: truncates toward zero"""
    q = abs(a) // abs(b)
    return q if (a >= 0) == (b > 0) else -q


def rows(vals, per=12, width=7):
    return "\n".join("    " + " ".join(f"{v:{width}d}," for v in vals[i:i + per]) for i in range(0, len(vals), per))


def main():
    vel = [4096 + cdiv(v * v * (32767 - 4096), 127 * 127) for v in (max(1, min(127, i)) for i in range(128))]
    kt = [max(-32768, min(32767, cdiv((k - 64) * 32767, 63))) for k in range(128)]
    depth = [cdiv(a * a * 4800, 127 * 127) for a in range(128)]
    # the knob tapers (2026-11-12, measured panel laws: the Juno-60's sliders against Roland's plugin, the
    # PicoVintageSynthCollection read): a depth's bottom third is fine control, its top the full range
    cut_env = [round(32 * a * a / 127) for a in range(128)]                 # square, 127: the whole cutoff range
    cut_lfo = [round(1536 * (3 * (a / 127) ** 2 - 2 * (a / 127) ** 3)) for a in range(128)]   # S-curve, 3.6 octaves
    wheel = [round(32766 * w * w / (127 * 127)) for w in range(128)]        # the wheel as a tapered pot
    sustain = [min(32766 << 15, round((1 << 30) * (1 - (1 - s / 127) ** 1.6))) for s in range(128)]
    cents = []
    for rem in range(1200):
        semi, frac = rem // 100, rem % 100
        cents.append(SEMI_Q16[semi] + ((SEMI_Q16[semi + 1] - SEMI_Q16[semi]) * frac) // 100)
    assert all(65536 <= c < 131072 for c in cents), "a cents ratio outside 16 bits over 65536"
    text = f"""/* Generated by src/dsp/gen_ctrl_tables.py: do not edit. The control tick's divides as tables (bit-exact). */
#pragma once
#include <stdint.h>

/* velocity_gain_q15: 4096 + v^2 * (32767 - 4096) / 127^2, v = velocity held to 1..127 */
static const int32_t ctrl_velocity_gain_q15[128] = {{
{rows(vel)}
}};

/* key_track_q15: (knob - 64) * 32767 / 63, held to Q15 */
static const int32_t ctrl_key_track_q15[128] = {{
{rows(kt)}
}};

/* pitch_mod_cents depth: amt^2 * 4800 / 127^2 cents at a full source */
static const int16_t ctrl_pitch_mod_depth[128] = {{
{rows(depth)}
}};

/* filter depth tapers, Q4 in ENV2 > CUTOFF's old units (a source at full times the entry, >> 12, is a Q8 cutoff
 * offset): ENV > CUTOFF and the cutoff routes 32 a^2 / 127, so 127 sweeps the whole cutoff range (was half of it,
 * linear) and 64 stays where it was; LFO1 > CUTOFF an S-curve to 3.6 octaves (48 knob steps) */
static const int16_t ctrl_cut_env_depth[128] = {{
{rows(cut_env)}
}};
static const int16_t ctrl_cut_lfo_depth[128] = {{
{rows(cut_lfo)}
}};

/* the mod wheel as a source, Q15: squared (a tapered pot: a gentle vibrato low on the wheel, full depth at the top) */
static const int32_t ctrl_wheel_q15[128] = {{
{rows(wheel)}
}};

/* apply_cents_q16 within an octave: 2^(rem / 1200) in Q16 for rem 0..1199, the semitone table interpolated, less
 * 65536 (every ratio is 65536 .. 131071: 16 bits hold it, half the flash of 32) */
static const uint16_t ctrl_cents_ratio_q16_lo[1200] = {{
{rows([c - 65536 for c in cents], per=10, width=7)}
}};
"""
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    env = f"""/* Generated by src/dsp/gen_ctrl_tables.py: do not edit. */
#pragma once
#include <stdint.h>

/* the SUSTAIN knob's level in Q30 (2026-11-12): 1 - (1 - s)^1.6, the Juno-60's measured law (a third of the way up
 * holds at 0.45; linear held 0.33), 127 at the old full level */
static const int32_t env_sustain_q30[128] = {{
{rows(sustain, per=6, width=11)}
}};
"""
    OUT_ENV.write_text(env, encoding="utf-8", newline="\n")
    print(f"wrote {OUT_ENV}")


if __name__ == "__main__":
    main()
