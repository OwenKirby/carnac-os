void osc_init(WavetableOsc *osc) {
    for (int i = 0; i < 4; i++) {
        osc->phases_q16[i] = 0;
        osc->step_increments[i] = 0;
    }
    osc->center_phase = 0;
    osc->bank = 0;
    osc->morph_q12 = 0;
    osc->xfade_q15 = 0;
    osc->pcm = (PcmOsc){0};
    osc_prepare(osc, 0, 0);
}

void osc_select_wave(WavetableOsc *osc, uint8_t code) {
    int kind = wave_kind(code);
    if (kind == 1 || kind == 2) {
        osc->pcm.code = code;
        osc->pcm.on = 1;
        return;
    }
    osc->pcm.on = 0;
    osc->pcm.code = 0;
    osc->bank = kind == 0 ? code % NUM_BANKS : 0;   /* a PCM wave the store does not hold: bank 0 */
}

/* Nyquist of the 44.1 kHz core (22050 Hz), in Q16. Level L holds harmonics up to (512 >> L) / 2, so it is
 * alias-free while f * ((512 >> L) / 2) <= Nyquist: its top frequency is Nyquist / ((512 >> L) / 2) = 44100 / (512 >> L). */
#define WT_NYQUIST_Q16 ((uint32_t)22050u << 16)
#define WT_LEVEL_TOP_Q16(level) (WT_NYQUIST_Q16 / ((WAVE_SAMPLES >> (level)) / 2u))

/* the top frequency of each level but the last; the last level (harmonics to 4) takes everything above */
static const uint32_t WT_LEVEL_TOP_TABLE_Q16[WT_LEVELS - 1] = {
    WT_LEVEL_TOP_Q16(0), WT_LEVEL_TOP_Q16(1), WT_LEVEL_TOP_Q16(2),
    WT_LEVEL_TOP_Q16(3), WT_LEVEL_TOP_Q16(4), WT_LEVEL_TOP_Q16(5),
};

uint8_t wt_level_for_freq(uint32_t frequency_q16) {
    for (uint8_t level = 0; level < WT_LEVELS - 1; level++)
        if (frequency_q16 <= WT_LEVEL_TOP_TABLE_Q16[level]) return level;
    return WT_LEVELS - 1;
}

