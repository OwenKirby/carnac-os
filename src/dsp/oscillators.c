/* Phase step per sample for a frequency in Q16 Hz: Hz * 2^32 / 44100 = (q16 >> 8) * 380.375, within 0.005 %. */
static uint32_t phase_step(uint32_t frequency_q16) {
    return ((frequency_q16 >> 8) * 380u) + (((frequency_q16 >> 8) * 3u) >> 3);
}

int32_t wt_read_morph(int bank, int morph_q12, uint8_t level, uint32_t phase) {
    int morph = morph_q12 >> 12;
    int32_t morph_frac_q15 = (morph_q12 & 0xFFF) << 3;
    if (morph >= NUM_MORPH_STEPS - 1) { morph = NUM_MORPH_STEPS - 1; morph_frac_q15 = 0; }

    const int16_t *frame = wavetable_frame(bank, morph, level);
    uint32_t shift = WT_LEVEL_SHIFT[level];
    uint32_t index_low = phase >> shift;
    uint32_t index_high = (index_low + 1u) & (WT_LEVEL_SAMPLES[level] - 1u);
    int32_t fraction_q15 = (int32_t)((phase & ((1u << shift) - 1u)) >> (shift - 15u));

    int32_t s_low_q15 = frame[index_low];
    int32_t a_q15 = s_low_q15 + (((frame[index_high] - s_low_q15) * fraction_q15) >> 15);
    if (morph_frac_q15 == 0) return a_q15;

    // The next frame of the same level, same offsets (not frame + WT_FRAME_SAMPLES: without a store image every
    // frame is the one sine, wavetable_attach.c)
    const int16_t *next = wavetable_frame(bank, morph + 1, level);
    s_low_q15 = next[index_low];
    int32_t b_q15 = s_low_q15 + (((next[index_high] - s_low_q15) * fraction_q15) >> 15);
    return a_q15 + (((b_q15 - a_q15) * morph_frac_q15) >> 15);
}

int16_t osc_process_skulpt_spread_fixed(WavetableOsc *osc, uint32_t frequency_q16, int raw_spread) {
    // OVERFLOW-SAFE PHASE ACCUMULATION
    // Shift frequency down BEFORE multiplying to prevent 32-bit integer register overflow wraps.
    // Step = Hz * 2^32 / 44100. In these units that is (q16 >> 8) * 380.375, within 0.005 %
    // (the old constant 382 was about 7 cents sharp).
    uint32_t base_step = phase_step(frequency_q16);

    /* The undetuned playhead always runs: it is the whole sound at spread 0 and fades into the detuned set
     * over the first SPREAD_XFADE values. At spread 0 the other four follow it, so a later spread starts from
     * one coherent wave and returning to 0 leaves no phase-offset copies behind (they would comb-filter the tone). */
    osc->center_phase += base_step;
    uint8_t center_level = wt_level_for_freq(frequency_q16);
    if (raw_spread <= 0) {
        osc->step_increments[0] = osc->step_increments[1] = osc->step_increments[2] = osc->step_increments[3] = base_step;
        osc->phases_q16[0] = osc->phases_q16[1] = osc->phases_q16[2] = osc->phases_q16[3] = osc->center_phase;
        return (int16_t)wt_read_morph(osc->bank, osc->morph_q12, center_level, osc->center_phase);
    }

    const uint32_t *ratio_q28 = spread_ratio_q28[raw_spread > 127 ? 127 : raw_spread];
    int32_t accumulated_mix_q15 = 0;

    for (int i = 0; i < 4; i++) {
        /* A playhead above Nyquist (a high note's +2 octave stack) is silent; it still keeps its phase. */
        uint64_t step = ((uint64_t)base_step * ratio_q28[i]) >> 28;
        if (step >= 0x80000000u) {
            osc->step_increments[i] = 0x80000000u;
            continue;
        }
        osc->step_increments[i] = (uint32_t)step;
        osc->phases_q16[i] += osc->step_increments[i];

        // Each playhead reads the mip level for its own pitch (see wt_level_for_freq), crossfaded between frames
        uint64_t freq = ((uint64_t)frequency_q16 * ratio_q28[i]) >> 28;
        uint8_t level = wt_level_for_freq(freq > 0xFFFFFFFFu ? 0xFFFFFFFFu : (uint32_t)freq);
        accumulated_mix_q15 += wt_read_morph(osc->bank, osc->morph_q12, level, osc->phases_q16[i]);
    }

    // Scale the combined 4-playhead output back down to Q15
    int32_t mix_q15 = accumulated_mix_q15 >> 2;
    if (raw_spread >= SPREAD_XFADE) return (int16_t)mix_q15;

    // Low spread: linear crossfade from the undetuned playhead (the two are nearly in phase here)
    int32_t center_q15 = wt_read_morph(osc->bank, osc->morph_q12, center_level, osc->center_phase);
    int32_t xfade_q15 = (raw_spread << 15) / SPREAD_XFADE;
    return (int16_t)(center_q15 + (((mix_q15 - center_q15) * xfade_q15) >> 15));
}

/* a playhead's table read at a mip level (wt_read_frames) */
static void osc_read_level(WavetableOsc *osc, int h, uint8_t level) {
    osc->rd_off[h] = wavetable_level_start[level];
    osc->rd_mask[h] = (uint16_t)(WT_LEVEL_SAMPLES[level] - 1u);
    osc->rd_shift[h] = WT_LEVEL_SHIFT[level];
}

void osc_prepare(WavetableOsc *osc, uint32_t frequency_q16, int raw_spread) {
    if (osc->pcm.on) {                              /* a PCM wave; the phase still turns, for the sub */
        osc->center_step = phase_step(frequency_q16);
        osc->xfade_q15 = 0;
        osc->live = 0;
        pcm_prepare(&osc->pcm, frequency_q16, osc->morph_q12);
        /* SPREAD: the loops' own detuned playheads at the bank's ratios and crossfade */
        if (raw_spread <= 0)
            pcm_spread(&osc->pcm, 0, 0);
        else
            pcm_spread(&osc->pcm, spread_ratio_q28[raw_spread > 127 ? 127 : raw_spread],
                       raw_spread >= SPREAD_XFADE ? 32768 : (raw_spread << 15) / SPREAD_XFADE);
        return;
    }
    /* the two frames either side of the scan (wt_read_morph's split), for every read this tick */
    int morph = osc->morph_q12 >> 12;
    int32_t morph_frac_q15 = (osc->morph_q12 & 0xFFF) << 3;
    if (morph >= NUM_MORPH_STEPS - 1) { morph = NUM_MORPH_STEPS - 1; morph_frac_q15 = 0; }
    osc->frame_a = wavetable_frames[osc->bank * NUM_MORPH_STEPS + morph];
    osc->frame_b = morph_frac_q15 ? wavetable_frames[osc->bank * NUM_MORPH_STEPS + morph + 1] : osc->frame_a;
    osc->morph_frac_q15 = morph_frac_q15;

    osc->center_step = phase_step(frequency_q16);
    osc->center_level = wt_level_for_freq(frequency_q16);
    osc_read_level(osc, 4, osc->center_level);
    if (raw_spread <= 0) {
        osc->live = 0;
        osc->xfade_q15 = 0;
        return;
    }
    /* spread 0 -> on: the four detuned playheads start from the undetuned one, so a spread starts from one coherent
     * wave and returning to 0 leaves no phase-offset copies behind (they would comb-filter the tone) */
    if (osc->xfade_q15 == 0)
        osc->phases_q16[0] = osc->phases_q16[1] = osc->phases_q16[2] = osc->phases_q16[3] = osc->center_phase;
    const uint32_t *ratio_q28 = spread_ratio_q28[raw_spread > 127 ? 127 : raw_spread];
    osc->live = 0;
    for (int i = 0; i < 4; i++) {
        /* A playhead above Nyquist (a high note's +2 octave stack) is silent; it keeps its phase. */
        uint64_t step = ((uint64_t)osc->center_step * ratio_q28[i]) >> 28;
        if (step >= 0x80000000u) {
            osc->step_increments[i] = 0x80000000u;
            continue;
        }
        osc->step_increments[i] = (uint32_t)step;
        uint64_t freq = ((uint64_t)frequency_q16 * ratio_q28[i]) >> 28;
        osc->levels[i] = wt_level_for_freq(freq > 0xFFFFFFFFu ? 0xFFFFFFFFu : (uint32_t)freq);
        osc_read_level(osc, i, osc->levels[i]);
        osc->live |= (uint8_t)(1u << i);
    }
    osc->xfade_q15 = raw_spread >= SPREAD_XFADE ? 32768 : (raw_spread << 15) / SPREAD_XFADE;
}

/* the undetuned playhead's read at its current phase */
static inline int32_t osc_read_center(const WavetableOsc *osc) {
    return wt_read_frames(osc->frame_a, osc->frame_b, osc->morph_frac_q15, osc->rd_off[4], osc->rd_shift[4],
                          osc->rd_mask[4], osc->center_phase);
}

int16_t osc_render(WavetableOsc *osc) {
    osc->center_phase += osc->center_step;
    if (osc->xfade_q15 == 0)        /* spread 0: the detuned playheads rejoin it when a spread starts (osc_prepare) */
        return (int16_t)osc_read_center(osc);
    int32_t mix_q15 = 0;
    for (int i = 0; i < 4; i++) {
        if (!(osc->live & (1u << i))) continue;
        osc->phases_q16[i] += osc->step_increments[i];
        mix_q15 += wt_read_frames(osc->frame_a, osc->frame_b, osc->morph_frac_q15, osc->rd_off[i], osc->rd_shift[i],
                                  osc->rd_mask[i], osc->phases_q16[i]);
    }
    mix_q15 >>= 2;
    if (osc->xfade_q15 >= 32768) return (int16_t)mix_q15;
    /* low spread: linear crossfade from the undetuned playhead (the two are nearly in phase here) */
    int32_t center_q15 = osc_read_center(osc);
    return (int16_t)(center_q15 + (((mix_q15 - center_q15) * osc->xfade_q15) >> 15));
}

/* SPREAD with all four playheads live: osc_render's sum and crossfade unrolled over the block, the phases and steps
 * held in locals (memory loads are the cost on the FM1 core). Bit-exact with osc_render. */
static void osc_render_spread4(WavetableOsc *osc, int32_t *out, int n) {
    const int16_t *fa = osc->frame_a, *fb = osc->frame_b;
    const int32_t mf = osc->morph_frac_q15, xf = osc->xfade_q15;
    const uint32_t o0 = osc->rd_off[0], o1 = osc->rd_off[1], o2 = osc->rd_off[2], o3 = osc->rd_off[3], oc = osc->rd_off[4];
    const uint32_t h0 = osc->rd_shift[0], h1 = osc->rd_shift[1], h2 = osc->rd_shift[2], h3 = osc->rd_shift[3],
                   hc = osc->rd_shift[4];
    const uint32_t m0 = osc->rd_mask[0], m1 = osc->rd_mask[1], m2 = osc->rd_mask[2], m3 = osc->rd_mask[3],
                   mc = osc->rd_mask[4];
    const uint32_t s0 = osc->step_increments[0], s1 = osc->step_increments[1], s2 = osc->step_increments[2],
                   s3 = osc->step_increments[3], sc = osc->center_step;
    uint32_t p0 = osc->phases_q16[0], p1 = osc->phases_q16[1], p2 = osc->phases_q16[2], p3 = osc->phases_q16[3],
             pc = osc->center_phase;
    for (int i = 0; i < n; i++) {
        pc += sc; p0 += s0; p1 += s1; p2 += s2; p3 += s3;
        int32_t mix_q15 = wt_read_frames(fa, fb, mf, o0, h0, m0, p0) + wt_read_frames(fa, fb, mf, o1, h1, m1, p1)
                        + wt_read_frames(fa, fb, mf, o2, h2, m2, p2) + wt_read_frames(fa, fb, mf, o3, h3, m3, p3);
        mix_q15 >>= 2;
        if (xf < 32768) {               /* low spread: the crossfade from the undetuned playhead */
            int32_t center_q15 = wt_read_frames(fa, fb, mf, oc, hc, mc, pc);
            mix_q15 = center_q15 + (((mix_q15 - center_q15) * xf) >> 15);
        }
        out[i] = (int16_t)mix_q15;
    }
    osc->phases_q16[0] = p0; osc->phases_q16[1] = p1; osc->phases_q16[2] = p2; osc->phases_q16[3] = p3;
    osc->center_phase = pc;
}

void osc_render_block(WavetableOsc *osc, int32_t *out, int n) {
    if (osc->pcm.on) {                              /* a PCM wave (pcm_osc.c); the phase turns on, for the sub */
        osc->center_phase += osc->center_step * (uint32_t)n;
        pcm_render_block(&osc->pcm, out, n);
        return;
    }
    if (osc->xfade_q15 != 0) {                 /* SPREAD: four playheads and the crossfade, as osc_render */
        if (osc->live == 0xF) {
            osc_render_spread4(osc, out, n);
            return;
        }
        for (int i = 0; i < n; i++)            /* a playhead above Nyquist (high notes, wide stacks) */
            out[i] = osc_render(osc);
        return;
    }
    /* wt_read_frames on the undetuned playhead, unrolled over the block (the phase steps before each read) */
    const int16_t *a = osc->frame_a + osc->rd_off[4], *b = osc->frame_b + osc->rd_off[4];
    uint32_t phase = osc->center_phase, step = osc->center_step, shift = osc->rd_shift[4], mask = osc->rd_mask[4];
    int32_t mf = osc->morph_frac_q15;
    for (int i = 0; i < n; i++) {
        phase += step;
        uint32_t i0 = phase >> shift, i1 = (i0 + 1u) & mask;
        int32_t fr_q15 = (int32_t)((phase << (32u - shift)) >> 17);
        int32_t s = a[i0];
        int32_t va = s + (((a[i1] - s) * fr_q15) >> 15);
        if (mf != 0) {
            s = b[i0];
            int32_t vb = s + (((b[i1] - s) * fr_q15) >> 15);
            va = va + (((vb - va) * mf) >> 15);
        }
        out[i] = (int16_t)va;
    }
    osc->center_phase = phase;
}

