#!/usr/bin/env python3
"""Writes src/dsp/ctrl_tables.h: the control tick's per-knob and per-cent results as tables, so the tick does a load
instead of a hardware divide (~24 cycles each on the FM1, which does not turn constant divides into multiplies).
Every entry is the integer formula synth_voice.c used before, with C's truncating division: bit-exact.

  python src/dsp/gen_ctrl_tables.py
"""
from pathlib import Path

OUT = Path(__file__).with_name("ctrl_tables.h")
SEMI_Q16 = [65536, 69433, 73562, 77936, 82570, 87480, 92682, 98193, 104032, 110218, 116772, 123715, 131072]


def cdiv(a, b):
    """C's integer division: truncates toward zero"""
    q = abs(a) // abs(b)
    return q if (a >= 0) == (b > 0) else -q


def rows(vals, per=12, width=7):
    return "\n".join("    " + " ".join(f"{v:{width}d}," for v in vals[i:i + per]) for i in range(0, len(vals), per))


def main():
    vel = [4096 + cdiv(v * v * (32767 - 4096), 127 * 127) for v in (max(1, min(127, i)) for i in range(128))]
    kt = [max(-32768, min(32767, cdiv((k - 64) * 32767, 63))) for k in range(128)]
    depth = [cdiv(a * a * 4800, 127 * 127) for a in range(128)]
    cents = []
    for rem in range(1200):
        semi, frac = rem // 100, rem % 100
        cents.append(SEMI_Q16[semi] + ((SEMI_Q16[semi + 1] - SEMI_Q16[semi]) * frac) // 100)
    text = f"""/* Generated by src/dsp/gen_ctrl_tables.py: do not edit. The control tick's divides as tables (bit-exact). */
#pragma once
#include <stdint.h>

/* velocity_gain_q15: 4096 + v^2 * (32767 - 4096) / 127^2, v = velocity held to 1..127 */
static const int32_t ctrl_velocity_gain_q15[128] = {{
{rows(vel)}
}};

/* key_track_q15: (knob - 64) * 32767 / 63, held to Q15 */
static const int32_t ctrl_key_track_q15[128] = {{
{rows(kt)}
}};

/* pitch_mod_cents depth: amt^2 * 4800 / 127^2 cents at a full source */
static const int16_t ctrl_pitch_mod_depth[128] = {{
{rows(depth)}
}};

/* apply_cents_q16 within an octave: 2^(rem / 1200) in Q16 for rem 0..1199, the semitone table interpolated */
static const uint32_t ctrl_cents_ratio_q16[1200] = {{
{rows(cents, per=10, width=7)}
}};
"""
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
