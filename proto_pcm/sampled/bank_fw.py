"""The REAL PCM images of the rebuilt bank (2026-11-06, proto_pcm/sampled/bank.py BANK=fit, 14 waves, one process):
the waves as bank_image.py builds them (rates, tails, HANDOFF flags, loudness ceiling), packed for the FM1:
  store area 0 (36 KiB, uploaded as 0)   the 14 WAVE entries, in the list's order, then samples
  store area 1 (56 KiB, uploaded as 1)   samples
  store area 3 (24 KiB, uploaded as 2)   samples (pcm_store.h PCM_AREA_ST2: Foundations' old place)
  store area 2 (the firmware, XIP)       the rest (pcm_area_fw.c), at most --fw-cap bytes
Writes src/dsp/pcm_area0.bin, pcm_area1.bin, pcm_area2.bin, src/dsp/pcm_area_fw.c, src/host/pcm_images_host.c.
  python bank_fw.py <repo> [--fw-cap BYTES]"""
import sys, struct, zlib, pathlib
here = pathlib.Path(__file__).parent.parent / "atkfit"
REPO = pathlib.Path(sys.argv[1])
FW_CAP = int(sys.argv[sys.argv.index("--fw-cap") + 1]) if "--fw-cap" in sys.argv else 0x24000
DSP = REPO / "src" / "dsp"
import os
os.environ["BANK"] = "fit"
SB = here.parent / "sampled"
sys.argv = [str(SB / "bank_image.py"), str(DSP), str(pathlib.Path(os.environ.get("TEMP", ".")) / "bank_fw_host.c")]
ns = {"__file__": str(SB / "bank_image.py"), "__name__": "bank_image"}
exec(compile(open(SB / "bank_image.py").read(), "bank_image.py", "exec"), ns)
ga, gp = ns["ga"], ns["gp"]
waves = {w["name"]: w for w in ns["waves"] if w["name"] != "CAIRN SPIRIT"}   # the classic one definitive_image adds
ORDER = ["CHOIR", "SPIRIT VOX", "PAN FLUTE", "HORNS", "STR ENS", "HOARFROST", "SINGING STN", "LORE", "BELL",
         "ROCK GONG", "RAINSTICK", "MENHIR", "LOG DRUM", "WOOD BLOCK"]   # factory_presets.c W_ enum order
assert sorted(ORDER) == sorted(waves), sorted(waves)
WS = [waves[n] for n in ORDER]

HDR, ENT, MAXE = 32, 36, 63
# the store's areas: index = the store's area number (pcm_store.h), size, the upload area (None: the firmware)
AREAS = {0: (0x9000, 0), 1: (0xE000, 1), 3: (0x6000, 2), 2: (FW_CAP, None)}
FILL = [0, 1, 3, 2]                      # store flash first, the firmware's area last


def blob(s):
    name, kind, root, rate, x = s
    q = bytes(int(v) & 0xFF for v in ga.mulaw_encode(ns["np"].clip(x, -1, 1)))
    return q + q[:1] if kind == 1 else q


samples = {}
for w in WS:
    for s in w["samples"]:
        assert s[0] not in samples, s[0]
        samples[s[0]] = s
used = {a: HDR for a in AREAS}
count = {a: 0 for a in AREAS}
used[0] += ENT * len(WS); count[0] += len(WS)
where = {}
for name in sorted(samples, key=lambda n: -len(blob(samples[n]))):
    need = len(blob(samples[name])) + ENT
    for a in FILL:
        if used[a] + need <= AREAS[a][0] and count[a] < MAXE:
            used[a] += need; count[a] += 1; where[name] = a
            break
    else:
        sys.exit(f"{name} does not fit: " + ", ".join(f"area {a} {used[a]}/{AREAS[a][0]}" for a in FILL))
order = {a: [n for n in samples if where[n] == a] for a in AREAS}
ref = {}
for a in AREAS:
    first = len(WS) if a == 0 else 0
    for i, n in enumerate(order[a]):
        ref[n] = (a << 6) | (first + i)

imgs = {}
for a in AREAS:
    entries, blobs = [], []
    off = HDR + ENT * ((len(WS) if a == 0 else 0) + len(order[a]))
    if a == 0:
        for w in WS:
            tl = w.get("tails", (0, 0))
            hand = w["fl"]
            entries.append(struct.pack("<12sBBBB BBBBBBHHBBBB6x", w["name"].encode()[:12].ljust(12, b"\0"), 3, 0, 0, 0,
                                       ref[w["la"]], ref[w["lb"]], ref[w["ka"]] if w["ka"] else 0xFF, 0xFF, w["lvl"], 0,
                                       4096, 0, (ref[w["kb"]] if w["kb"] else 0xFF) if hand else 0, hand,
                                       tl[0] if hand else 0, tl[1] if hand else 0))
    for n in order[a]:
        name, kind, root, rate, x = samples[n]
        b = blob(samples[n])
        entries.append(struct.pack("<12sBBBBIIIII", name.encode()[:12].ljust(12, b"\0"), kind, root, 0, 0,
                                   int(round(rate)), off, len(x), 0, 0))
        blobs.append(b); off += len(b)
    body = b"".join(entries) + b"".join(blobs)
    h = struct.pack("<IHHII12x", gp.MAGIC, gp.VERSION, len(entries), HDR + len(body), zlib.crc32(body))
    img = h + struct.pack("<I", zlib.crc32(h)) + body
    assert len(img) <= AREAS[a][0]
    imgs[a] = img


def c_array(name, img):
    out = [f"const uint32_t {name}_len = {len(img)}u;", f"_Alignas(4) const uint8_t {name}[{len(img)}] = {{"]
    out += ["    " + ",".join(str(b) for b in img[i:i + 24]) + "," for i in range(0, len(img), 24)]
    return out + ["};"]


for a, (size, up) in AREAS.items():
    if up is not None:
        (DSP / f"pcm_area{up}.bin").write_bytes(imgs[a])
fw = ["/* Generated by proto_pcm/sampled/bank_fw.py (2026-11-06, the rebuilt bank): do not edit. The PCM store's",
      " * firmware area (pcm_store.h PCM_AREA_FW): samples that live in the app itself, read in place (XIP on the FM1);",
      " * pcm_store.c attaches it with the first area attached. */", "#include <stdint.h>", ""]
(DSP / "pcm_area_fw.c").write_text("\n".join(fw + c_array("pcm_image_fw", imgs[2])) + "\n", encoding="ascii")
host = ["/* Generated by proto_pcm/sampled/bank_fw.py: do not edit. The PCM store's uploaded images (pcm_store.h), for",
        " * host builds only: pcm_image_host<N> is uploaded area N (the store's area 0, 1, 3: attach host2 as",
        " * PCM_AREA_ST2); the FM1 reads them from the flash they were uploaded to (pcm_store_fm1.c). */",
        "#include <stdint.h>", ""]
for a, (size, up) in AREAS.items():
    if up is not None:
        lines = c_array(f"pcm_image_host{up}", imgs[a])
        lines[0] = f"const uint32_t pcm_image_host_len{up} = {len(imgs[a])}u;"
        host += lines
(REPO / "src" / "host" / "pcm_images_host.c").write_text("\n".join(host) + "\n", encoding="ascii")
tot = sum(len(b) for b in imgs.values())
print("areas: " + ", ".join(f"store {a} {len(imgs[a])}/{AREAS[a][0]} B ({count[a]} entries)" for a in FILL))
print(f"total {tot} B ({tot / 1024:.1f} KiB); waves: " + ", ".join(ORDER))
